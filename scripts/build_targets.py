#!/usr/bin/env python3
"""Generate the VS Code and Antigravity layouts from the canonical plugin source.

The toolkit is authored once, in the Cursor plugin layout at the repository root.
Every other host gets its copy from this script rather than from a parallel set of
hand-maintained files, because three hand-maintained copies drift, and a drifted
safety rule is worse than an absent one: it is a guardrail a user still believes in.

What differs between hosts is packaging, not judgement. Skills are already an open
standard and travel unchanged. Rules become `AGENTS.md`. Commands become prompt
files on VS Code and skills on Antigravity. Hook wiring differs in event names and
reply shapes, which `hooks/host_contract.py` absorbs, so the gate scripts ship
byte-identical everywhere and reach the same verdict on each host.

Usage:
    python3 scripts/build_targets.py            # write dist/
    python3 scripts/build_targets.py --check    # verify dist/ matches the source
"""

from __future__ import annotations

import argparse
import filecmp
import json
import re
import shutil
import tempfile
from dataclasses import dataclass, field
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parent.parent
PLUGIN_ROOT_TOKEN = "${CURSOR_PLUGIN_ROOT}"

# Development and installation scripts are not invoked by agent workflows.
# They stay out of generated targets so an installed toolkit carries only what
# it runs.
DEV_ONLY_SCRIPTS = frozenset(
    {
        "build_targets.py",
        "install_target.py",
    }
)

GENERATED_NOTICE = (
    "Generated by scripts/build_targets.py from the canonical plugin source. "
    "Edit the source and rebuild; changes made here are overwritten."
)


@dataclass(frozen=True)
class Target:
    """Where one host expects each kind of asset to live."""

    name: str
    # Path from the workspace root to the toolkit's own scripts, references, and
    # hook executables. Skill and command text is rewritten to point at it.
    shared_root: str
    skills_dir: str
    agents_dir: str
    agent_suffix: str
    hooks_config: str
    mcp_config: str
    # Commands become prompt files where the host has them, and skills where it
    # does not, since a skill is the portable way to expose a named workflow.
    commands_dir: str | None = None
    command_suffix: str = ".prompt.md"
    commands_as_skills: bool = False
    notes: tuple[str, ...] = field(default_factory=tuple)


TARGETS: dict[str, Target] = {
    "antigravity": Target(
        name="antigravity",
        shared_root=".agents/ae-toolkit",
        skills_dir=".agents/skills",
        agents_dir=".agents/agents",
        agent_suffix=".md",
        hooks_config=".agents/hooks.json",
        mcp_config=".agents/mcp_config.json",
        commands_as_skills=True,
        notes=(
            "Antigravity resolves a relative hook command against the directory the "
            "session started in, and a hook that fails to launch does not block the "
            "tool call it was meant to gate. Run scripts/install_target.py to stamp "
            "absolute paths into .agents/hooks.json.",
        ),
    ),
    "vscode": Target(
        name="vscode",
        shared_root=".github/ae-toolkit",
        skills_dir=".github/skills",
        agents_dir=".github/agents",
        agent_suffix=".agent.md",
        hooks_config=".github/hooks/ae-toolkit.json",
        mcp_config=".vscode/mcp.json",
        commands_dir=".github/prompts",
        command_suffix=".prompt.md",
    ),
}


def read_text(path: Path) -> str:
    return path.read_text(encoding="utf-8")


def split_frontmatter(text: str) -> tuple[dict[str, str], str]:
    """Return the YAML frontmatter as flat key-values, plus the body.

    Frontmatter in this repository is deliberately flat -- `name`, `description`,
    `alwaysApply` -- so a full YAML parser is unnecessary and would add a
    dependency to a toolkit that promises the standard library only.
    """
    if not text.startswith("---"):
        return {}, text
    parts = text.split("---", 2)
    if len(parts) < 3:
        return {}, text
    meta: dict[str, str] = {}
    for line in parts[1].splitlines():
        stripped = line.strip()
        if not stripped or stripped.startswith("#") or ":" not in line:
            continue
        key, _, value = line.partition(":")
        meta[key.strip()] = value.strip().strip('"').strip("'")
    return meta, parts[2].lstrip("\n")


def retarget(text: str, target: Target) -> str:
    """Point plugin-root references at the location this host installs into.

    Token substitution only, so it is safe to apply to executable code.
    """
    return text.replace(PLUGIN_ROOT_TOKEN, target.shared_root)


def shipped_references() -> frozenset[str]:
    """The reference documents every target carries, since the tree ships whole."""
    return frozenset(path.name for path in (REPO_ROOT / "references").glob("*.md"))


def retarget_doc(text: str, target: Target, shipped: frozenset[str]) -> str:
    """Rewrite the bare script and reference paths that appear in guidance text.

    Most guidance names a script through the plugin-root token, but some writes it
    bare, as `scripts/redact_secrets.py`. Under Cursor both resolve; on these hosts
    the bare form points at a `scripts/` directory in the user's own repository,
    which is either absent or, worse, someone else's code. Left alone it produces
    an instruction the agent cannot carry out -- and the one instance of it guards
    secret redaction before cloud transmission, so silently breaking it would
    weaken the privacy boundary rather than merely inconvenience a workflow.

    Reference documents have exactly the same problem and it went unnoticed longer,
    because a missing `references/privacy.md` reads as an ordinary broken link
    rather than a disabled control. It is not: the always-applied rules delegate the
    privacy handling, the severity scale, the vocabulary, and the warehouse
    portability guidance to those files, so on a host where the path does not
    resolve the agent is left with the summary and not the rule.

    Only what the target actually carries is rewritten, so a reference to something
    absent stays visibly wrong instead of being disguised as a working path. The
    lookbehind prevents rewriting a path the token substitution just produced.
    """
    text = retarget(text, target)
    rewritable = [f"scripts/{name}" for name in shipped]
    rewritable += [f"references/{name}" for name in shipped_references()]
    for relative in sorted(rewritable):
        text = re.sub(
            rf"(?<![\w/.]){re.escape(relative)}",
            f"{target.shared_root}/{relative}",
            text,
        )
    return text


def write(path: Path, content: str) -> None:
    path.parent.mkdir(parents=True, exist_ok=True)
    if not content.endswith("\n"):
        content += "\n"
    path.write_text(content, encoding="utf-8")


def doc_sources() -> list[Path]:
    """Every authored file whose text reaches a generated target."""
    return [
        *(REPO_ROOT / "skills").rglob("*.md"),
        *(REPO_ROOT / "commands").glob("*.md"),
        *(REPO_ROOT / "agents").glob("*.md"),
        *(REPO_ROOT / "rules").glob("*.mdc"),
    ]


def runtime_scripts() -> list[Path]:
    """Select the scripts a shipped target actually needs.

    Derived from what the shipped guidance invokes, then closed over sibling
    imports, so adding a script to a workflow ships it automatically and retiring
    one stops shipping it. A hardcoded list would quietly go stale.

    Rules are scanned alongside skills and commands because they ship too, as
    `AGENTS.md`. Omitting them once cost the target its secret-redaction script.
    """
    source = REPO_ROOT / "scripts"
    referenced: set[str] = set()
    for doc in doc_sources():
        referenced.update(re.findall(r"scripts/([A-Za-z0-9_]+\.py)", read_text(doc)))

    known = {path.name for path in source.glob("*.py")}
    pending = sorted(referenced & known)
    resolved: set[str] = set()
    while pending:
        name = pending.pop()
        if name in resolved:
            continue
        resolved.add(name)
        for module in re.findall(r"^\s*(?:import|from)\s+([A-Za-z0-9_]+)", read_text(source / name), re.M):
            sibling = f"{module}.py"
            if sibling in known and sibling not in resolved:
                pending.append(sibling)

    return sorted(source / name for name in resolved - DEV_ONLY_SCRIPTS)


def copy_tree(source: Path, destination: Path, target: Target, shipped: frozenset[str]) -> None:
    for item in sorted(source.rglob("*")):
        if item.is_dir() or "__pycache__" in item.parts:
            continue
        out = destination / item.relative_to(source)
        out.parent.mkdir(parents=True, exist_ok=True)
        if item.suffix in {".md", ".mdc"}:
            write(out, retarget_doc(read_text(item), target, shipped))
        elif item.suffix in {".py", ".json", ".yml", ".yaml"}:
            write(out, retarget(read_text(item), target))
        else:
            shutil.copy2(item, out)


def build_agents_md(target: Target, shipped: frozenset[str]) -> str:
    """Fold the always-applied rules into the file every host reads.

    Cursor loads `.mdc` rules with their own frontmatter. VS Code and Antigravity
    both read `AGENTS.md`, so the rules are concatenated into one document with
    their descriptions preserved as context rather than dropped.
    """
    sections: list[str] = [
        "# Analytics Engineering Toolkit",
        "",
        f"<!-- {GENERATED_NOTICE} -->",
        "",
        "These directives always apply in this repository. They are the toolkit's "
        "operating rules, carried over from its Cursor plugin rules so that behaviour "
        "is identical across hosts.",
        "",
    ]
    for rule in sorted((REPO_ROOT / "rules").glob("*.mdc")):
        meta, body = split_frontmatter(read_text(rule))
        description = meta.get("description", "").strip()
        if description:
            sections.extend([f"> {description}", ""])
        sections.extend([retarget_doc(body, target, shipped).strip(), ""])
    return "\n".join(sections).strip()


def build_hooks_config(target: Target) -> str:
    """Wire both gates into the host's blocking pre-tool event.

    Cursor separates shell and MCP into two events; these hosts multiplex every
    tool through one, so both gates are registered and each stands aside for
    traffic that is not its own.
    """
    shell = f"python3 {target.shared_root}/hooks/safety_gate.py --host {target.name}"
    cloud = f"python3 {target.shared_root}/hooks/cloud_data_gate.py --host {target.name}"

    if target.name == "vscode":
        # No matcher: VS Code parses matchers but currently ignores them, running
        # every hook on every tool call. The gates therefore filter their own
        # traffic, which is also what makes the same scripts work on Antigravity,
        # where the matcher is honoured.
        config: dict = {
            "hooks": {
                "PreToolUse": [
                    {"type": "command", "command": shell, "timeoutSec": 10},
                    {"type": "command", "command": cloud, "timeoutSec": 10},
                ]
            }
        }
    else:
        config = {
            "ae-toolkit-safety": {
                "enabled": True,
                "PreToolUse": [
                    {
                        "matcher": "run_command",
                        "hooks": [{"type": "command", "command": shell, "timeout": 10}],
                    },
                    {
                        "matcher": "call_mcp_tool",
                        "hooks": [{"type": "command", "command": cloud, "timeout": 10}],
                    },
                ],
            }
        }
    return json.dumps(config, indent=2)


def build_mcp_config(target: Target) -> str:
    source = json.loads(read_text(REPO_ROOT / "mcp.json"))
    if target.name == "vscode":
        # VS Code nests servers under "servers" rather than "mcpServers".
        return json.dumps({"servers": source.get("mcpServers", source)}, indent=2)
    return json.dumps(source, indent=2)


def build_command(path: Path, target: Target, out_root: Path, shipped: frozenset[str]) -> None:
    meta, body = split_frontmatter(read_text(path))
    name = meta.get("name", path.stem)
    description = meta.get("description", "").strip()
    body = retarget_doc(body, target, shipped).strip()

    if target.commands_as_skills:
        # A skill is how a host without prompt files exposes a named workflow,
        # and the command frontmatter is already a valid skill header.
        #
        # This host makes commands model-invocable, so `ae-build-model` and
        # `build-model` become two selectable entries describing one job. The
        # command is the shorter of the two, so a router that picks the alias
        # would quietly deliver less work than the skill it fronts. Naming the
        # canonical skill keeps the answer the same whichever entry is chosen.
        canonical = re.search(r"Apply the `([a-z0-9-]+)` skill", body)
        if canonical and (REPO_ROOT / "skills" / canonical.group(1) / "SKILL.md").is_file():
            body = (
                f"This is the `{name}` alias of the `{canonical.group(1)}` skill. "
                f"Follow that skill's full procedure and output contract; the summary "
                f"below orients the request and does not replace it.\n\n" + body
            )
        front = ["---", f"name: {name}", f"description: {description}", "---", ""]
        write(out_root / target.skills_dir / name / "SKILL.md", "\n".join(front) + body)
        return

    assert target.commands_dir is not None
    front = ["---", f"description: {description}", "agent: agent", "---", ""]
    write(out_root / target.commands_dir / f"{name}{target.command_suffix}", "\n".join(front) + body)


def build_target(target: Target, out_root: Path) -> None:
    if out_root.exists():
        shutil.rmtree(out_root)
    out_root.mkdir(parents=True)

    scripts = runtime_scripts()
    shipped = frozenset(script.name for script in scripts)

    copy_tree(REPO_ROOT / "skills", out_root / target.skills_dir, target, shipped)

    for command in sorted((REPO_ROOT / "commands").glob("*.md")):
        build_command(command, target, out_root, shipped)

    for agent in sorted((REPO_ROOT / "agents").glob("*.md")):
        meta, body = split_frontmatter(read_text(agent))
        name = meta.get("name", agent.stem)
        front = ["---", f"name: {name}", f"description: {meta.get('description', '').strip()}", "---", ""]
        write(
            out_root / target.agents_dir / f"{name}{target.agent_suffix}",
            "\n".join(front) + retarget_doc(body, target, shipped).strip(),
        )

    shared = out_root / target.shared_root
    for script in scripts:
        write(shared / "scripts" / script.name, read_text(script))
    copy_tree(REPO_ROOT / "references", shared / "references", target, shipped)
    for hook in sorted((REPO_ROOT / "hooks").glob("*.py")):
        write(shared / "hooks" / hook.name, read_text(hook))

    write(out_root / target.hooks_config, build_hooks_config(target))
    write(out_root / target.mcp_config, build_mcp_config(target))
    write(out_root / "AGENTS.md", build_agents_md(target, shipped))


def differences(fresh: Path, committed: Path) -> list[str]:
    """Compare two trees by content, reporting every path that disagrees."""
    problems: list[str] = []
    fresh_files = {p.relative_to(fresh) for p in fresh.rglob("*") if p.is_file()}
    committed_files = {p.relative_to(committed) for p in committed.rglob("*") if p.is_file()}

    problems.extend(f"missing from committed output: {p}" for p in sorted(fresh_files - committed_files))
    problems.extend(f"stale file in committed output: {p}" for p in sorted(committed_files - fresh_files))
    problems.extend(
        f"content differs: {p}"
        for p in sorted(fresh_files & committed_files)
        if not filecmp.cmp(fresh / p, committed / p, shallow=False)
    )
    return problems


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument(
        "--check",
        action="store_true",
        help="verify the committed targets match the source instead of writing them",
    )
    parser.add_argument("--target", choices=sorted(TARGETS), help="build only one target")
    args = parser.parse_args()

    selected = [TARGETS[args.target]] if args.target else [TARGETS[key] for key in sorted(TARGETS)]
    dist = REPO_ROOT / "dist"

    if args.check:
        problems: list[str] = []
        with tempfile.TemporaryDirectory() as tmp:
            for target in selected:
                fresh = Path(tmp) / target.name
                build_target(target, fresh)
                committed = dist / target.name
                if not committed.exists():
                    problems.append(f"{target.name}: dist/{target.name} has not been generated")
                    continue
                problems.extend(f"{target.name}: {issue}" for issue in differences(fresh, committed))
        if problems:
            print("Generated targets are out of date with the plugin source:")
            for problem in problems:
                print(f"  {problem}")
            print("\nRun: python3 scripts/build_targets.py")
            return 1
        print(f"Targets are in sync with the source: {', '.join(t.name for t in selected)}")
        return 0

    for target in selected:
        build_target(target, dist / target.name)
        print(f"Built dist/{target.name}")
        for note in target.notes:
            print(f"  note: {note}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
